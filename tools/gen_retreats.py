def mirror_photo(url, slug, check=False):
    """Bring the program photo onto our own domain.

    og:image has to be an absolute URL on a host that will still serve it when
    somebody pastes the link into WhatsApp a month from now — and the preview
    card is most of the reason these pages exist."""
    if not url:
        return None, ''
    # An entry in data/retreats-extra.json names a photo we already host — the
    # Himalayan pilgrimage's, mirrored for /retreats long before this script.
    # Use it where it lies; assets/ is sync_assets.py's to own, not ours.
    if url.startswith('/assets/'):
        master = ROOT / url.lstrip('/')
        if not master.exists():
            print('    missing photo %s' % url)
            return None, ''
        return url, ''
    ext = os.path.splitext(url.split('?')[0])[1].lower() or '.jpg'
    if ext not in ('.jpg', '.jpeg', '.png', '.webp'):
        ext = '.jpg'
    master = ASSET_DIR / (slug + ext)
    rel = '/' + str(master.relative_to(ROOT)).replace(os.sep, '/')
    if not master.exists():
        if check:
            return rel, ''
        ASSET_DIR.mkdir(parents=True, exist_ok=True)
        master.write_bytes(fetch(url))
        print('    photo %s' % rel)
    try:
        from PIL import Image
    except ImportError:
        return rel, ''
    with Image.open(master) as im:
        nat_w, nat_h = im.size
        entries = []
        for w in [w for w in LADDER if w < nat_w]:
            out = ROOT / 'assets' / 'r' / 'retreats' / 'rg' / ('%s-%dw.webp' % (slug, w))
            if not out.exists() and not check:
                out.parent.mkdir(parents=True, exist_ok=True)
                copy = im.convert('RGBA' if 'A' in im.getbands() else 'RGB')
                h = max(1, round(nat_h * w / nat_w))
                copy.resize((w, h), Image.LANCZOS).save(out, 'WEBP', quality=82, method=6)
            if out.exists():
                entries.append('/%s %dw' % (str(out.relative_to(ROOT)).replace(os.sep, '/'), w))
    entries.append('%s %dw' % (rel, nat_w))
    return rel, ', '.join(entries)


def social_card(local, slug, check=False):
    """The image a link preview actually shows, as its own file.

    Not the master: one of these is a 2.2MB PNG, and og:image is fetched by
    every chat app that ever sees the link. Not a WebP either — the size ladder
    is WebP and the page uses it, but LinkedIn and older Mail/Messages builds
    still show nothing for a WebP card. So: JPEG, longest side 1200, no crop.
    Cropping to Facebook's 1.91:1 would take the top off a square portrait, and
    every scraper crops to its own frame anyway."""
    if not local:
        return None, 0, 0
    master = ROOT / local.lstrip('/')
    if not master.exists():
        return None, 0, 0
    out = ASSET_DIR / (slug + '-card.jpg')
    rel = '/' + str(out.relative_to(ROOT)).replace(os.sep, '/')
    try:
        from PIL import Image
    except ImportError:
        return local, 0, 0
    with Image.open(master) as im:
        w, h = im.size
        scale = min(1.0, 1200 / max(w, h))
        size = (max(1, round(w * scale)), max(1, round(h * scale)))
        if not out.exists() and not check:
            out.parent.mkdir(parents=True, exist_ok=True)
            copy = im.convert('RGB')
            if scale < 1.0:
                copy = copy.resize(size, Image.LANCZOS)
            copy.save(out, 'JPEG', quality=82, optimize=True, progressive=True)
            print('    card %s (%dx%d)' % (rel, *size))
    return (rel if out.exists() else local), size[0], size[1]


