def text(s):
    """Retreat Guru double-escapes some titles ("Redding, Ca &#8211; ...")."""
    return htmllib.unescape(htmllib.unescape(s or '')).strip()


def esc(s):
    return htmllib.escape(text(s), quote=True)


def plain(s, limit=None):
    s = re.sub(r'<[^>]+>', ' ', s or '')
    s = re.sub(r'\s+', ' ', htmllib.unescape(s)).strip()
    if limit and len(s) > limit:
        s = s[:limit].rsplit(' ', 1)[0].rstrip(' ,;:.—–-') + '…'
    return s


# Attributes worth keeping on the program body. Everything else — WordPress and
# ChatGPT both leave a trail of data-start / data-section-id / class="isSelected"
# on every paragraph — is noise that would also have to be styled around.
KEEP_ATTRS = {'href', 'src', 'alt', 'title', 'width', 'height', 'colspan', 'rowspan'}
BLOCKED_TAGS = re.compile(r'<(script|style|iframe|form|input|noscript)\b.*?</\1>|<(script|style|iframe|form|input|noscript)\b[^>]*/?>', re.S | re.I)
TAG = re.compile(r'<(/?)([a-zA-Z][a-zA-Z0-9]*)((?:\s+[^\s=>]+(?:\s*=\s*(?:"[^"]*"|\'[^\']*\'|[^\s>]+))?)*)\s*(/?)>')
ATTR = re.compile(r'([^\s=]+)\s*=\s*"([^"]*)"|([^\s=]+)\s*=\s*\'([^\']*)\'')


def clean_body(raw):
    """Retreat Guru's rich text, reduced to what this site can style.

    Nothing here is rewritten for meaning — tags are dropped, attributes are
    dropped, headings are demoted one level so the page keeps a single h1, and
    that is all."""
    if not raw:
        return ''
    body = BLOCKED_TAGS.sub('', raw)

    def one(m):
        close, name, attrs, self_close = m.group(1), m.group(2).lower(), m.group(3), m.group(4)
        # h1 in the body would be a second document title: the page already has
        # one, and it is the same words. Demote the whole heading run with it so
        # the outline stays ordered.
        name = {'h1': 'h2', 'h2': 'h3', 'h3': 'h4', 'h4': 'h5'}.get(name, name)
        if close:
            return '</%s>' % name
        kept = []
        for a in ATTR.finditer(attrs):
            key = (a.group(1) or a.group(3)).lower()
            val = a.group(2) if a.group(2) is not None else a.group(4)
            if key in KEEP_ATTRS:
                kept.append('%s="%s"' % (key, htmllib.escape(val, quote=True)))
        if name == 'a':
            kept += ['target="_blank"', 'rel="noopener"']
        if name == 'img':
            kept.append('loading="lazy"')
        return '<%s%s%s>' % (name, (' ' + ' '.join(kept)) if kept else '', ' /' if self_close else '')

    body = TAG.sub(one, body)
    # Empty paragraphs survive the attribute strip as <p></p>; the runtime drops
    # whitespace-only ones anyway, so take them out here where it is visible.
    body = re.sub(r'<p>(?:\s|&nbsp;)*</p>', '', body)
    # The Design Component runtime interpolates {{ ... }}. A program description
    # containing braces would be compiled as an expression and render as nothing.
    body = body.replace('{{', '&#123;&#123;').replace('}}', '&#125;&#125;')
    return body.strip()


