// Retreat Guru links back to "our website" from its own pages — the centre's
// programs list, and each teacher profile such as
// https://paititi-institute.secure.retreat.guru/teacher/roman-hanis/. It builds
// those links from one field in the Retreat Guru admin, as
//
//     <website>/?programs=1&program=<id>
//
// which is how the RBG Connect widget deep-links into a program when the widget
// is embedded on the page that field names. Through the migration that field
// still read paititi-institute.squarespace.com, so every one of those links led
// back to the old Squarespace site (Roman, 25 Aug 2026).
//
// Our widget lives inside an iframe (/rbg-widget.html), so the query string
// never reaches it and the deep link would otherwise just sit unused on
// whichever page it landed on. This maps the program id onto the page that
// actually presents that program, so the field can simply be set to
// https://paititi-institute.org and every link resolves.
//
// Every program — the in-person ones at /retreats/<slug> and the self-paced
// courses at /online-courses/<slug> — now has a page of its own, so an id lands
// on that program rather than on the listing that contains it. All of these
// rows are generated: re-run tools/gen_retreats.py when a program is added or
// retired, and do not add one by hand, because the next run would drop it.
//
// (The four course ids used to be hand-written here, pointing at anchors
// partway down /online-courses. They came out when the courses got pages.)
//
// An unrecognised id is left alone on purpose — better a real page with a stray
// query string than a confident redirect to the wrong program.
(() => {
  var DESTINATIONS = {
  // BEGIN destinations (generated by tools/gen_retreats.py)
    1083: '/retreats/grass-valley-ca-seed-of-the-heart-children-parent-workshop-on-emotions-nature-ancestral-wisdom',
    1103: '/retreats/nevada-city-ca-beyond-ayahuasca-book-talk-amazonian-based-breathwork',
    1105: '/retreats/nevada-city-ca-amazonian-ashuar-based-indigenous-dreamwork',
    1104: '/retreats/nevada-city-ca-amazonian-tibetan-primordial-breathwork-w-ceremonial-cacao',
    1092: '/retreats/san-francisco-ca-amazonian-ashuar-based-indigenous-dreamwork',
    1078: '/retreats/san-francisco-bay-beyond-psychedelics-yet-not-without',
    1046: '/retreats/amazon-16-day-embodying-true-nature-immersion',
    614: '/online-courses/your-evolutionary-blueprint-online-home-study-course',
    632: '/online-courses/alchemy-of-immortality-daoist-qigong-andean-art-of-being-online-home-study-course',
    638: '/online-courses/primordial-breathwork-online-home-study-course-series',
    997: '/online-courses/beyond-ayahuasca-book-practical-alchemy-series',
  // END destinations
  };

  var id = new URLSearchParams(location.search).get('program');
  if (!id || !/^\d+$/.test(id)) return;
  var to = DESTINATIONS[id];
  if (!to) return;
  // replace(), not assign(): the query-string URL is a redirect step, not a
  // page the reader should be able to go Back to.
  if (location.pathname + location.hash !== to) location.replace(to);
})();
